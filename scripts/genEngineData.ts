// GENERATES src-tauri/src/engine_data.rs from the TypeScript definitions.
//   npx tsx scripts/genEngineData.ts
//
// WHY A GENERATOR
// B2 moves the semantic checks into Rust, but the reference data -- ~900 wa.*
// function names, five handle classes and their members, the receiver registry --
// is authored in TypeScript and must stay there: it is documentation the user
// edits, and the front end still needs it for autocomplete.
//
// Hand-maintaining a second copy in Rust is how the two drift apart, which is the
// exact failure data/handleRegistry.ts exists to prevent. So this emits a Rust
// source file at BUILD time and it is included with include_str!/include! -- baked
// into the binary, so there is no runtime asset path to break in the Tauri bundle.
//
// RE-RUN after editing wormforgeDefinitions.ts or handleRegistry.ts, or Rust will
// silently check your code against stale engine API data:
//
//   npx tsx scripts/genEngineData.ts           # regenerate
//   npx tsx scripts/genEngineData.ts --check   # verify; exit 1 if stale
//
// The staleness check lives HERE, not in `cargo test`. Rust cannot recompute a hash of
// the TypeScript arrays, so the only honest test is to regenerate and compare on this
// side. (An earlier version of this comment claimed `cargo test` failed on a stale file.
// It did not, and nothing was checking -- hence `--check`.)
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { BUILTIN_FUNCTIONS, BUILTIN_CLASSES } from '../src/data/wormforgeDefinitions';
import { RECEIVER_REGISTRY, ALL_HANDLE_CLASSES, ITERATOR_ELEMENT } from '../src/data/handleRegistry';
import { LUA_GLOBALS } from '../src/data/luaGlobals';
import { WORM_STATES, SETTABLE_WORM_STATES } from '../src/data/wormStates';
import { WEAPON_SPEC_KEYS } from '../src/data/specKeys';

const rustStr = (s: string): string => JSON.stringify(s);

const lines: string[] = [];
lines.push('// @generated by scripts/genEngineData.ts -- DO NOT EDIT BY HAND.');
lines.push('//');
lines.push('// Source of truth:');
lines.push('//   src/data/wormforgeDefinitions.ts  (BUILTIN_FUNCTIONS, BUILTIN_CLASSES)');
lines.push('//   src/data/handleRegistry.ts        (RECEIVER_REGISTRY, ALL_HANDLE_CLASSES, ITERATOR_ELEMENT)');
lines.push('//   src/data/luaGlobals.ts            (LUA_GLOBALS)');
lines.push('//   src/data/wormStates.ts           (WORM_STATES, SETTABLE_WORM_STATES)');
lines.push('//   src/data/specKeys.ts              (WEAPON_SPEC_KEYS)');
lines.push('//');
lines.push('// Re-run: npx tsx scripts/genEngineData.ts');
lines.push('// Verify: npx tsx scripts/genEngineData.ts --check  (exit 1 if stale)');
lines.push('');
lines.push('/// Every `wa.*` function path the engine exposes. Used by the namespace-typo');
lines.push('/// check, which needs to know that `wa.weapons.replace` exists but');
lines.push('/// `wa.weapons.repalce` does not.');
lines.push(`pub static WA_FUNCTIONS: &[&str] = &[`);
for (const f of BUILTIN_FUNCTIONS) lines.push(`    ${rustStr(f.name)},`);
lines.push('];');
lines.push('');

// Handle classes: only the five the registry resolves to, and only their METHOD
// members -- the checker warns about unknown methods, so properties are irrelevant.
const HANDLE_CLASSES = new Set([
  'WormEntity',
  'LuaActor',
  'WorldHandle',
  'MissileEntity',
  'InventoryStore',
  'LightHandle',
  'MagneticField',
]);

lines.push('/// (class name, method names) for the handle classes the checker resolves.');
lines.push('pub static HANDLE_CLASSES: &[(&str, &[&str])] = &[');
for (const cls of BUILTIN_CLASSES) {
  if (!HANDLE_CLASSES.has(cls.name)) continue;
  const methods = cls.members.filter((m) => m.kind === 'method').map((m) => m.name);
  lines.push(`    (${rustStr(cls.name)}, &[`);
  for (const m of methods) lines.push(`        ${rustStr(m)},`);
  lines.push('    ]),');
}
lines.push('];');
lines.push('');

// ALL members -- methods AND properties -- in the order the TypeScript union check
// consults them (`ALL_HANDLE_CLASSES` in handleRegistry.ts).
//
// WHY A SECOND TABLE: the `handle-union` rule asks "does ANY handle class have this
// member?" with no kind filter (parser.ts `members.some(name)`). Measured against the
// TS baseline: `m:id()` is SILENT because `id` is a MissileEntity property even though
// MissileEntity has no methods at all, and a ducked `obj:phase()` passes as a union
// notice because MissileEntity has `phase`. A methods-only answer would emit a
// different rule id than the baseline, which scripts/__sweep.ts counts as drift.
lines.push('/// (class name, EVERY member name -- methods and properties) for the');
lines.push('/// handle-union check, in the order parser.ts `ALL_HANDLE_CLASSES` consults them.');
lines.push('///');
lines.push('/// GENERATED: members from wormforgeDefinitions.ts, order from handleRegistry.ts.');
lines.push('pub static HANDLE_ALL_MEMBERS: &[(&str, &[&str])] = &[');
for (const clsName of ALL_HANDLE_CLASSES) {
  const cls = BUILTIN_CLASSES.find((c) => c.name === clsName);
  if (!cls) throw new Error(`ALL_HANDLE_CLASSES names "${clsName}", absent from BUILTIN_CLASSES`);
  lines.push(`    (${rustStr(clsName)}, &[`);
  for (const m of cls.members) lines.push(`        ${rustStr(m.name)},`);
  lines.push('    ]),');
}
lines.push('];');
lines.push('');

lines.push('/// The receiver registry: (prefix, class, rule, note).');
lines.push('///');
lines.push('/// `diagnose` is the subset the CHECKER claims, which is deliberately smaller');
lines.push('/// than `prefixes`: a wrong guess on the checker is a false error on valid');
lines.push('/// code, which is the disease this whole work exists to cure.');
lines.push('pub static RECEIVERS: &[(&str, &str, &str, &str)] = &[');
for (const row of RECEIVER_REGISTRY) {
  const names = row.diagnose ?? row.prefixes;
  for (const p of names) {
    lines.push(`    (${rustStr(p.toLowerCase())}, ${rustStr(row.className)}, ${rustStr(row.rule)}, ${rustStr(row.note ?? '')}),`);
  }
}
lines.push('];');
lines.push('');

// Globals + state keys. These were hand-kept in checks.rs while parser.ts kept its own
// copies, and the two global lists had already drifted by nine names before this
// generator covered them. Emitting them here means `--check` covers them too, so the
// Rust and TypeScript sides cannot silently diverge a second time.
// `wa.X.all()` iterator element types. `wa.missiles.all()` yields WorldHandle
// userdata, NOT the MissileEntity table `wa.on.missile_frame` passes -- the two are
// different values and the engine proves it (`spawn.rs` `bind_kind_list` ->
// `objects_table` -> `WorldHandle::new`). Emitting this is what lets the Rust
// checker resolve `for _, missile in ipairs(wa.missiles.all()) do missile:impulse()
// end` the way the TypeScript one does; without it both engines fell back to the
// NAME `missile`, resolved to MissileEntity, and warned on valid code.
lines.push('/// `(wa.X.all, handle class)` -- what a `for _, v in <wa.X.all()>` loop binds.');
lines.push('///');
lines.push('/// GENERATED from src/data/handleRegistry.ts (`ITERATOR_ELEMENT`). A loop over one');
lines.push('/// of these is a FACT about the value; a receiver NAME is only a convention, so');
lines.push('/// the trace is consulted first and the name table second.');
lines.push('pub static LOOP_ELEMENT: &[(&str, &str)] = &[');
for (const [iter, cls] of Object.entries(ITERATOR_ELEMENT)) {
  lines.push(`    (${rustStr(iter.toLowerCase())}, ${rustStr(cls)}),`);
}
lines.push('];');
lines.push('');

lines.push("/// Globals a mod may legitimately read: the Lua 5.4 library plus the engine's own `wa`.");
lines.push('///');
lines.push('/// GENERATED from src/data/luaGlobals.ts. The exclusions that list documents --');
lines.push('/// `unpack`/`bit32` (removed from Lua), `bit`/`jit` (LuaJIT-isms), and');
lines.push('/// `game_state`/`run_once`/`printf` (never injected by the host; api.rs:329 sets');
lines.push('/// only `wa`) -- are pinned by a test in checks.rs so they cannot come back.');
lines.push('pub static KNOWN_GLOBALS: &[&str] = &[');
for (const g of LUA_GLOBALS) lines.push(`    ${rustStr(g)},`);
lines.push('];');
lines.push('');

// Worm states, from the ENGINE (crates/game/src/worm_state.rs and
// crates/lua-host/src/actor.rs). This REPLACES a fabricated `wa.game_state(...)
// .states.KEY` list that described an API the engine never had.
lines.push('/// Every worm state the engine can label: (name, raw WA 3.8.1 id, confirmed).');
lines.push('///');
lines.push('/// GENERATED from src/data/wormStates.ts. `confirmed` is false where the');
lines.push('/// engine\'s own label carries a `?` (one observation only) -- those must never');
lines.push('/// justify a finding on working code.');
lines.push('pub static WORM_STATES: &[(&str, u32, bool)] = &[');
for (const s of WORM_STATES) lines.push(`    (${rustStr(s.name)}, ${s.id}, ${s.confirmed}),`);
lines.push('];');
lines.push('');

// The ONLY list a checker may enforce: what `worm:set_state("...")` accepts.
lines.push('/// Every name `worm:set_state("...")` accepts: (name, raw id).');
lines.push('///');
lines.push('/// GENERATED from src/data/wormStates.ts. Mirrors `settable_worm_state()` in');
lines.push('/// crates/lua-host/src/actor.rs exactly -- do NOT widen it from WORM_STATES. The');
lines.push('/// engine rejects every other name as a hard Lua error, including real states');
lines.push('/// that are simply not settable ("jetpacking" is pinned as None in its tests).');
lines.push('pub static WORM_SETTABLE_STATES: &[(&str, u32)] = &[');
for (const s of SETTABLE_WORM_STATES) lines.push(`    (${rustStr(s.name)}, ${s.id}),`);
lines.push('];');
lines.push('');

lines.push('/// Keys accepted inside a `wa.weapons.replace({...})` / `register({...})` spec table.');
lines.push('///');
lines.push('/// GENERATED from src/data/specKeys.ts. That list errs toward INCLUSION: a real');
lines.push('/// key missing here produces a false positive, never an error.');
lines.push('pub static SPEC_KEYS: &[&str] = &[');
for (const k of WEAPON_SPEC_KEYS) lines.push(`    ${rustStr(k)},`);
lines.push('];');
lines.push('');

const out = join('src-tauri', 'src', 'engine_data.rs');
const text = lines.join('\n');

// `--check` regenerates in memory and compares instead of writing. This is the only
// honest way to answer "is engine_data.rs stale relative to the TypeScript data?", and
// it lives here rather than in `cargo test` because Rust cannot recompute a TypeScript
// hash. Exit 1 so it can gate a build or a pre-commit step.
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current === text) {
    console.log(`${out} is up to date (${BUILTIN_FUNCTIONS.length} wa.* functions).`);
    process.exit(0);
  }
  console.error(
    `${out} is STALE. Re-run: npx tsx scripts/genEngineData.ts\n` +
      `  Rust would otherwise check your code against outdated engine API data.`
  );
  process.exit(1);
}

writeFileSync(out, text, 'utf8');
console.log(
  `wrote ${out}\n` +
    `  WA_FUNCTIONS:    ${BUILTIN_FUNCTIONS.length}\n` +
    `  HANDLE_CLASSES:  ${BUILTIN_CLASSES.filter((c) => HANDLE_CLASSES.has(c.name)).length}\n` +
    `  RECEIVERS:       ${RECEIVER_REGISTRY.reduce((n, r) => n + (r.diagnose ?? r.prefixes).length, 0)}\n` +
    `  LOOP_ELEMENT:    ${Object.keys(ITERATOR_ELEMENT).length}\n` +
    `  KNOWN_GLOBALS:   ${LUA_GLOBALS.length}\n` +
    `  WORM_STATES:     ${WORM_STATES.length}\n` +
    `  SETTABLE_STATES: ${SETTABLE_WORM_STATES.length}\n` +
    `  SPEC_KEYS:       ${WEAPON_SPEC_KEYS.length}`
);