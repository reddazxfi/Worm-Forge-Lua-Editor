// GENERATES src/data/recordFields.ts from the engine's own field table.
//
//   npx tsx scripts/genRecordFields.ts          # regenerate
//   npx tsx scripts/genRecordFields.ts --check  # exit 1 if stale
//
// WHY FROM THE ENGINE'S JSON, NOT BY HAND
// `wa.weapons.replace` and `wa.weapons.launch` do not take free-form tables.
// Every leaf is a named field in `crates/weapons/src/record.rs`, and the engine
// already publishes that list as JSON for its own web weapon editor
// (`record_fields.json`, written by `fields_json()` and kept current by a test
// there). Transcribing ~110 paths by hand would be a second copy of engine data,
// which is exactly how the API tables drifted before.
//
// The file is checked in because the app must build without the engine source.
// services/__tests__/recordFields.test.ts compares it back to the engine JSON and
// skips loudly when that folder is absent.
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

interface EngineRow {
  path: string;
  off: number;
  kind: 'int' | 'bool' | 'sprite' | { enum: Record<string, number> };
  families: string[];
  action: number | null;
  body: boolean;
}

const SRC = join('WormForge-main-source', 'web', 'weapon-editor', 'record_fields.json');
const OUT = join('src', 'data', 'recordFields.ts');

if (!existsSync(SRC)) {
  console.error(`${SRC} is missing. Record-field data cannot be generated without the engine tree.`);
  process.exit(1);
}

const rows: EngineRow[] = JSON.parse(readFileSync(SRC, 'utf8'));

const lines: string[] = [];
lines.push('// @generated by scripts/genRecordFields.ts -- DO NOT EDIT BY HAND.');
lines.push('//');
lines.push('// Source of truth: crates/weapons/src/record.rs `fields()` in the engine,');
lines.push('// published as WormForge-main-source/web/weapon-editor/record_fields.json');
lines.push('// (written by `fields_json()`, kept current by a test in that crate).');
lines.push('//');
lines.push('// Regenerate: npx tsx scripts/genRecordFields.ts');
lines.push('// Verify:     npx tsx scripts/genRecordFields.ts --check');
lines.push('');
lines.push('/** How a record field reads in Lua. `enum` carries the accepted names. */');
lines.push("export type RecordFieldKind = 'int' | 'bool' | 'sprite' | 'enum';");
lines.push('');
lines.push('export interface RecordFieldRow {');
lines.push('  /** Its place in the table, e.g. `missile.explosion.power`. */');
lines.push('  path: string;');
lines.push('  /** Entry offset in a non-strike weapon record. Shown as provenance only. */');
lines.push('  off: number;');
lines.push('  kind: RecordFieldKind;');
lines.push('  /** Accepted names, for `enum` fields. */');
lines.push('  values?: [string, number][];');
lines.push('  /** Weapon families whose records have the field. */');
lines.push('  families: string[];');
lines.push('  /** 1 = homing, 2 = bounce; the field exists only under that missile action. */');
lines.push('  action: number | null;');
lines.push('  /** A missile-body field: 0x14 further on in a strike record. */');
lines.push('  body: boolean;');
lines.push('}');
lines.push('');
lines.push('/** Missile action (`missile.action`) that gates some body fields. */');
lines.push('export const RECORD_ACTIONS: Record<number, string> = { 1: \'homing\', 2: \'bounce\' };');
lines.push('');
lines.push('export const RECORD_FIELDS: RecordFieldRow[] = [');
for (const r of rows) {
  const kind = typeof r.kind === 'string' ? r.kind : 'enum';
  const values = typeof r.kind === 'string'
    ? ''
    : `, values: [${Object.entries(r.kind.enum).map(([k, v]) => `['${k}', ${v}]`).join(', ')}]`;
  lines.push('  {');
  lines.push(`    path: ${JSON.stringify(r.path)},`);
  lines.push(`    off: ${r.off},`);
  lines.push(`    kind: '${kind}'${values},`);
  lines.push(`    families: [${r.families.map((f) => `'${f}'`).join(', ')}],`);
  lines.push(`    action: ${r.action === null ? 'null' : r.action},`);
  lines.push(`    body: ${r.body},`);
  lines.push('  },');
}
lines.push('];');
lines.push('');

const text = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current === text) {
    console.log(`${OUT} is up to date (${rows.length} record fields).`);
    process.exit(0);
  }
  console.error(`${OUT} is STALE. Re-run: npx tsx scripts/genRecordFields.ts`);
  process.exit(1);
}

writeFileSync(OUT, text, 'utf8');
console.log(`wrote ${OUT}\n  RECORD_FIELDS: ${rows.length}`);
