// The vendoring direction, pinned.
//
// WHY THIS TEST EXISTS
// `compiler-cli/src/{checks,scopes,engine_data}.rs` are VENDORED copies of the
// app's `src-tauri/src/` files. They are byte-identical AT COPY TIME; the CLI owns
// its copy afterwards so it builds with the app absent (compiler-cli/tests/
// drift.rs: "The wire-shape test used to read the app's src-tauri/src/main.rs...
// It can't anymore: this folder must build with the app absent.").
//
// That makes the copies the most drift-prone files in the repo, and the drift is
// SILENT. It already happened: engine_data.rs was a pre-API-4 snapshot while
// checks.rs was current, so `wfcheck` warned `a:warp() is not a LuaActor method`
// on valid code -- a method that exists, in the engine, and in the copy the app
// was using. Nothing failed. `cargo test` in the CLI passed 222 tests against the
// stale table, because every test asserts the checker's behaviour, not the
// table's contents.
//
// THE DIRECTION
//   src/data/*.ts  --(genEngineData.ts)-->  src-tauri/src/engine_data.rs
//                          --(copy)-->       compiler-cli/src/engine_data.rs
// The app generates. The CLI is handed the result. Never edit the CLI copy to
// fix a finding: edit the TypeScript, regenerate, copy, and the next `cargo test`
// proves both sides agree.
import { describe, it, expect } from 'vitest';
import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const APP = resolve(ROOT, 'src-tauri/src');
const CLI = resolve(ROOT, 'compiler-cli/src');

/** The files the CLI vendors. Keep in step with compiler-cli/tests/drift.rs. */
const VENDORED = ['checks.rs', 'scopes.rs', 'engine_data.rs'] as const;

describe('the vendored checker files are in lockstep', () => {
  it.each(VENDORED)('%s is byte-identical in the app and the CLI', (name) => {
    const appPath = resolve(APP, name);
    const cliPath = resolve(CLI, name);
    expect(existsSync(appPath), `${appPath} is missing`).toBe(true);
    expect(existsSync(cliPath), `${cliPath} is missing`).toBe(true);

    const app = readFileSync(appPath, 'utf8');
    const cli = readFileSync(cliPath, 'utf8');

    if (app === cli) return;
    // A line-level diff, not a byte count: "they differ" does not tell the next
    // person WHICH direction to fix it, and getting that backwards is how the
    // stale engine_data.rs survived in the first place.
    const appLines = app.split('\n');
    const cliLines = cli.split('\n');
    const onlyInApp = appLines.filter((l) => !cli.includes(l)).slice(0, 10);
    const onlyInCli = cliLines.filter((l) => !app.includes(l)).slice(0, 10);

    throw new Error(
      `${name} has drifted between the app and the CLI.\n` +
        `  app: ${appLines.length} lines, cli: ${cliLines.length} lines\n` +
        `  only in src-tauri/src/${name}: ${JSON.stringify(onlyInApp)}\n` +
        `  only in compiler-cli/src/${name}: ${JSON.stringify(onlyInCli)}\n` +
        `Fix it in the APP (edit src/data/*.ts, run\n` +
        `  npx tsx scripts/genEngineData.ts\n` +
        `then copy src-tauri/src/${name} over compiler-cli/src/${name}), never by\n` +
        `editing the CLI copy -- that is what reintroduced the stale API-4 table.`
    );
  });

  it('the CLI is the one holding the copy, not the generator', () => {
    // A one-line reminder of the direction, asserted so that moving the CLI back
    // to being the source of truth fails loudly rather than by inspection later.
    const cli = readFileSync(resolve(CLI, 'engine_data.rs'), 'utf8');
    expect(cli).toContain('@generated by scripts/genEngineData.ts -- DO NOT EDIT BY HAND.');
  });
});